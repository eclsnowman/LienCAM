# Desk build of the bridge, to the ONE canonical path.
#
# WHY THIS SCRIPT EXISTS AND WHY IT TAKES NO OUTPUT PATH.
# Windows Firewall identifies a program by its FULL PATH. Every lane that built
# the bridge into its own temp directory - liencam-wo1130-build,
# liencam-bridge-wo1130, liencam-bridge-desk-1130fix, liencam-wo1124-build, and
# 888 more by 2026-09-10 - produced a binary Windows had never seen, so the operator got
# an "allow this app through the firewall" dialog on his own workstation, over
# and over, for our test builds. He had accumulated 66 firewall rules (14 Allow,
# 52 Block) before anyone noticed.
#
# The bridge listens on LOOPBACK ONLY and refuses anything else at startup
# (Bridge.cs: `IPAddress.IsLoopback(bindAddr)` or Exit(2)), so it never needed a
# firewall grant at all. The dialogs were pure noise generated by us.
#
# So: one path, always. Build here, run here. Do not add a -OutDir parameter,
# do not append a WO number, do not make it unique "just for this run" - that is
# precisely the bug. If you need two binaries at once (an A/B control), use the
# bridge's own --inject-* flags, which run the SAME binary both ways by design.

$ErrorActionPreference = 'Stop'

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$out  = Join-Path $env:TEMP 'liencam-bridge-desk'
$root = Join-Path $env:TEMP 'liencam-bridge-desk-uccnc'
$exe  = Join-Path $out 'liencam-bridge.exe'
$sourceRoot = if ($env:LIENCAM_DESK_SOURCE_ROOT) { $env:LIENCAM_DESK_SOURCE_ROOT } else {
  Split-Path -Parent (git -C $here rev-parse --path-format=absolute --git-common-dir)
}
$boardSource = Join-Path $here 'boards'
$boardOutput = Join-Path $out 'boards'

function Get-Sha256([string]$path) {
  $sha = [Security.Cryptography.SHA256]::Create()
  $stream = $null
  try {
    $stream = [IO.File]::OpenRead($path)
    return ([BitConverter]::ToString($sha.ComputeHash($stream))).Replace('-', '')
  }
  finally {
    if ($stream -ne $null) { $stream.Dispose() }
    $sha.Dispose()
  }
}

New-Item -ItemType Directory -Force $out, "$root\API\DLL", "$root\Profiles" | Out-Null

# UC100_wrapper.cs is CNCdrive's proprietary header and is gitignored, so a
# runner worktree does not have it. It lives in the main checkout.
$wrapper = Join-Path $here 'UC100_wrapper.cs'
if (-not (Test-Path $wrapper)) {
  $fromMain = (Join-Path $sourceRoot 'pendant\uccnc-bridge\UC100_wrapper.cs')
  if (-not (Test-Path $fromMain)) { throw "UC100_wrapper.cs not found here or at $fromMain" }
  Copy-Item $fromMain $wrapper -Force
  Write-Output "copied UC100_wrapper.cs from the main checkout"
}

$csc = 'C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe'
& $csc /nologo /unsafe /platform:x64 /target:winexe /out:"$exe" `
    (Join-Path $here 'Bridge.cs') (Join-Path $here 'Machine.cs') `
    (Join-Path $here 'Json.cs')   (Join-Path $here 'Vfd.cs') $wrapper
if ($LASTEXITCODE -ne 0) { throw "csc failed with exit $LASTEXITCODE" }

# Board pin tables are product data beside the executable. Replace the staged
# directory as one unit so a table removed from source cannot survive as stale
# build output and silently make an unsupported board look supported.
if (-not (Test-Path -LiteralPath $boardSource)) {
  throw "board table source directory not found: $boardSource"
}
if (Test-Path -LiteralPath $boardOutput) {
  $resolvedOut = [IO.Path]::GetFullPath($out).TrimEnd('\')
  $resolvedBoards = [IO.Path]::GetFullPath($boardOutput)
  if (-not $resolvedBoards.StartsWith("$resolvedOut\", [StringComparison]::OrdinalIgnoreCase)) {
    throw "refusing to replace board output outside the canonical desk build: $resolvedBoards"
  }
  Remove-Item -LiteralPath $boardOutput -Recurse -Force
}
Copy-Item -LiteralPath $boardSource -Destination $boardOutput -Recurse -Force

# The bridge refuses to start unless it resolves the profile, API\DLL\UC100.dll
# under the install root, and ftd2xx64.dll AT the root.
$bin = Join-Path $here 'bin'
if (-not (Test-Path (Join-Path $bin 'UC100.dll'))) { $bin = (Join-Path $sourceRoot 'pendant\uccnc-bridge\bin') }
Copy-Item (Join-Path $bin 'UC100.dll')  "$root\API\DLL\UC100.dll" -Force
Copy-Item (Join-Path $bin 'FTD2XX.dll') "$root\ftd2xx64.dll"      -Force
Copy-Item (Join-Path $sourceRoot 'docs\machine\profiles\LienCNCV2.pro') "$root\Profiles\" -Force
@{ installRoot = $root; profile = 'LienCNCV2.pro'; board = -19 } | ConvertTo-Json |
    Set-Content (Join-Path $out 'liencam-bridge.config.json') -Encoding utf8

$info = Get-Item $exe
$exeHash = Get-Sha256 $exe
Write-Output "exe      $exe"
Write-Output "bytes    $($info.Length)"
Write-Output "written  $($info.LastWriteTime.ToString('s'))"
Write-Output "sha256   $exeHash"
Write-Output "profile  $root\Profiles\LienCNCV2.pro"
foreach ($boardFile in @(Get-ChildItem -LiteralPath $boardOutput -Filter '*.json' -File | Sort-Object Name)) {
  $boardHash = Get-Sha256 $boardFile.FullName
  Write-Output "board    $($boardFile.Name) $($boardFile.Length) bytes sha256 $boardHash"
}
Write-Output ""
Write-Output "run it:  Start-Process '$exe' -ArgumentList '--board','-19','--port','8399' -WorkingDirectory '$out'"
