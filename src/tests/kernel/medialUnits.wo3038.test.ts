// WO-3038 (alpha.3 A3-07): the kernel medial-axis service's filters on hand-built shapes with
// a known skeleton, its parity policy, and determinism.

import { beforeAll, describe, expect, it } from 'vitest'
import * as kernel from '../../kernel/medial'
import { medialAxis as todayAxis } from '../../lib/cam/vcarve2d/medialAxis'
import { buildRegions, ensureVCarveClipperReady } from '../../lib/cam/vcarve2d'
import { outlineTextToContours } from '../../lib/sketch/textOutline'

type P = { x: number; y: number }
const rect = (w: number, h: number): P[] => [{ x: 0, y: 0 }, { x: w, y: 0 }, { x: w, y: h }, { x: 0, y: h }]
const circle = (r: number, n: number, noise = 0): P[] => Array.from({ length: n }, (_, i) => {
  const a = (2 * Math.PI * i) / n
  // Deterministic wobble: a polygonised, imperfect circle.
  const rr = r + noise * Math.sin(7 * i) * Math.cos(3 * i)
  return { x: rr * Math.cos(a), y: rr * Math.sin(a) }
})
// A T: bar 40 x 8 on a stem 8 wide and 25 long. Six convex corners, two reflex, and a shallow
// bump (0.3 mm over 4 mm, a 9 deg turn: not a corner) on the bar's top edge that grows a spur.
const TEE: P[] = [
  { x: 16, y: 0 }, { x: 24, y: 0 }, { x: 24, y: 25 }, { x: 40, y: 25 }, { x: 40, y: 33 },
  { x: 22, y: 33 }, { x: 20, y: 33.3 }, { x: 18, y: 33 }, { x: 0, y: 33 }, { x: 0, y: 25 }, { x: 16, y: 25 },
]
const TEE_CONVEX: P[] = [{ x: 16, y: 0 }, { x: 24, y: 0 }, { x: 40, y: 25 }, { x: 40, y: 33 }, { x: 0, y: 33 }, { x: 0, y: 25 }]

const service = kernel.createMedialService()
const ends = (paths: kernel.AxisPath[]) => paths.filter(p => !p.closed && p.points.length > 1).flatMap(p => [p.points[0], p.points[p.points.length - 1]])
const near = (a: P, b: P, eps = 1e-9) => Math.hypot(a.x - b.x, a.y - b.y) <= eps

/** Leaves of a graph (live nodes with one live neighbour) and the corners they run into. */
function leaves(graph: kernel.MedialGraph) {
  return graph.nodes.flatMap((n, id) => n.alive && kernel.degree(graph.nodes, id) === 1 ? [{ id, node: n }] : [])
}

/** The construction alone: every candidate edge, or only the non-secondary ones, no pruning. */
function unfiltered(region: kernel.Region, spacing: number, keepSecondary: boolean): kernel.MedialGraph {
  const normal = kernel.normalizeRegion(region)
  const built = kernel.construct(normal, spacing, (40 * Math.PI) / 180)
  kernel.connect(built.nodes, keepSecondary ? built.edges : kernel.removeSecondaryEdges(built.edges))
  return built
}

beforeAll(async () => { await ensureVCarveClipperReady() })

describe('WO-3038 filters on shapes with a known skeleton', () => {
  it('rectangle 40 x 10: one centre line at r = 5 and four corner branches ending at the corners with r = 0', () => {
    const paths = service.axis({ outer: rect(40, 10), holes: [] }, { spacing: 0.1 })
    expect(paths).toHaveLength(5)
    const spine = paths.filter(p => p.points.every(q => Math.abs(q.y - 5) < 1e-6 && Math.abs(q.r - 5) < 1e-6))
    expect(spine).toHaveLength(1)
    const xs = spine[0].points.map(q => q.x).sort((a, b) => a - b)
    expect(xs[0]).toBeCloseTo(5, 6)
    expect(xs[xs.length - 1]).toBeCloseTo(35, 6)
    const cornerEnds = ends(paths).filter(q => q.r === 0)
    for (const corner of rect(40, 10)) expect(cornerEnds.some(q => near(q, corner)), `${corner.x},${corner.y}`).toBe(true)
    expect(cornerEnds).toHaveLength(4)
    // Every node is its clearance radius from the boundary (r = distance to the nearest wall).
    for (const q of paths.flatMap(p => p.points)) expect(q.r).toBeCloseTo(Math.min(q.x, 40 - q.x, q.y, 10 - q.y), 6)
  })

  it('secondary-edge removal: the spurs a sampled wall grows toward itself are dropped, and only they', () => {
    // A 40 x 20 rectangle with a thin slanted slot (a hole 0.2 wide) along its middle, sampled
    // at 1 mm. Between two consecutive samples of a slot wall, the Voronoi edge runs from the
    // centre line (y ~ 5 or ~ 15) straight at the wall: a spur generated by the wall itself.
    const slot: P[] = [{ x: 10, y: 9.9 }, { x: 10.5, y: 10.1 }, { x: 30.5, y: 10.1 }, { x: 30, y: 9.9 }]
    const region = { outer: rect(40, 20), holes: [slot] }
    const atSlot = (n: P) => n.y > 9 && n.y < 11 && n.x > 9.5 && n.x < 31
    const onCentreLine = (n: P) => n.y < 6 || n.y > 14
    const raw = unfiltered(region, 1, true)
    const toWall = (e: kernel.CandidateEdge) => {
      const a = raw.nodes[e.a], b = raw.nodes[e.b]
      return (atSlot(a) && onCentreLine(b)) || (atSlot(b) && onCentreLine(a))
    }
    const secondary = raw.edges.filter(e => e.secondary)
    expect(secondary.length).toBeGreaterThan(20)
    expect(secondary.filter(e => !toWall(e))).toEqual([])
    const kept = kernel.removeSecondaryEdges(raw.edges)
    expect(kept).toHaveLength(raw.edges.length - secondary.length)
    expect(kept.filter(toWall)).toEqual([])
  })

  it('a T: spurs are pruned, and every surviving leaf runs into one of its six convex corners', () => {
    const region = { outer: TEE, holes: [] }
    const before = unfiltered(region, 0.25, false)
    // Before pruning: the bump's spur is the one leaf that runs into no corner.
    const spurs = leaves(before).filter(l => !l.node.corner)
    expect(spurs).toHaveLength(1)
    expect(Math.abs(spurs[0].node.x - 20)).toBeLessThan(1)
    expect(spurs[0].node.y).toBeGreaterThan(29)
    const after = service.graph(region, { spacing: 0.25 })!
    expect(leaves(after).filter(l => !l.node.corner)).toEqual([])
    const paths = service.axis(region, { spacing: 0.25 })
    const cornerEnds = ends(paths).filter(q => q.r === 0)
    expect(cornerEnds).toHaveLength(6)
    for (const corner of TEE_CONVEX) expect(cornerEnds.some(q => near(q, corner)), `${corner.x},${corner.y}`).toBe(true)
    // The reflex corners grow no branch.
    for (const reflex of [{ x: 24, y: 25 }, { x: 16, y: 25 }]) expect(ends(paths).some(q => near(q, reflex, 1e-6))).toBe(false)
  })

  it('a noisy polygonised circle: no spur survives; the axis collapses to one point site near the centre', () => {
    const result = service.analyse({ outer: circle(10, 240, 0.02), holes: [] }, { spacing: 0.1 })
    expect(result.paths).toHaveLength(1)
    expect(result.pointSites).toHaveLength(1)
    expect(Math.hypot(result.pointSites[0].x, result.pointSites[0].y)).toBeLessThan(0.1)
    expect(result.pointSites[0].r).toBeGreaterThan(9.9)
  })

  it('length prune: a two-leaf component shorter than the prune length keeps only its deepest node', () => {
    const nodes: kernel.GraphNode[] = [0, 1, 2].map(i => ({ x: i * 0.1, y: 0, r: [1, 3, 2][i], circumradius: 3, adj: [], corner: null, sep: Math.PI, alive: true }))
    kernel.connect(nodes, [{ a: 0, b: 1, secondary: false }, { a: 1, b: 2, secondary: false }])
    kernel.pruneShortLeaves(nodes, 1)
    expect(nodes.map(n => n.alive)).toEqual([false, true, false])
  })

  it('radius trim: a corner branch trimmed at r = 2 ends exactly where the clearance is 2', () => {
    const paths = service.axis({ outer: rect(40, 10), holes: [] }, { spacing: 0.1 })
    const corner = paths.find(p => p.points[0].r === 0 && near(p.points[0], { x: 0, y: 0 }))
      ?? paths.find(p => p.points[p.points.length - 1].r === 0 && near(p.points[p.points.length - 1], { x: 0, y: 0 }))!
    const pieces = service.trimByRadius(corner, 2)
    expect(pieces).toHaveLength(1)
    const tip = pieces[0].find(q => q.r === 2)!
    expect(tip.x).toBeCloseTo(2, 6)
    expect(tip.y).toBeCloseTo(2, 6)
    expect(pieces[0].every(q => q.r <= 2)).toBe(true)
    // The spine (r = 5 everywhere) lies wholly above the bound: nothing kept.
    const spine = paths.find(p => p.points.every(q => Math.abs(q.r - 5) < 1e-6))!
    expect(service.trimByRadius(spine, 2)).toEqual([])
    // A closed chain starts at its widest point, so a kept arc is one piece across the seam.
    const ring: kernel.AxisPath = { closed: true, points: [{ x: 0, y: 0, r: 1 }, { x: 1, y: 0, r: 3 }, { x: 1, y: 1, r: 1 }, { x: 0, y: 1, r: 1 }] }
    const kept = service.trimByRadius(ring, 2)
    expect(kept).toHaveLength(1)
    expect(kept[0].map(q => q.r)).toEqual([2, 1, 1, 1, 2])
  })
})

describe('WO-3038 policies at parity', () => {
  it('MD-112 and MD-134 are off by default and each names card V23', () => {
    expect(kernel.PARITY_MEDIAL_POLICY).toEqual({ vcarve_dot_plunge: 'off', vcarve_flat_clearing: 'built_in' })
    expect(service.policy).toBe(kernel.PARITY_MEDIAL_POLICY)
    expect(Object.keys(kernel.CARDED_MEDIAL_ALTERNATIVES).sort()).toEqual(Object.keys(kernel.PARITY_MEDIAL_POLICY).sort())
    expect(kernel.CARDED_MEDIAL_ALTERNATIVES.vcarve_dot_plunge).toMatchObject({ named: 'MD-112', card: 'V23' })
    expect(kernel.CARDED_MEDIAL_ALTERNATIVES.vcarve_flat_clearing).toMatchObject({ named: 'MD-134', card: 'V23' })
  })

  it('flags off reproduce today: a lone dot is one point site with no motion, and the axis is today\'s', () => {
    const dot = { outer: circle(0.3, 48), holes: [] }
    const result = service.analyse(dot, { spacing: 0.08 })
    expect(result.paths).toEqual(todayAxis(dot, { spacing: 0.08 }))
    expect(result.pointSites).toHaveLength(1)
    expect(Object.keys(result).sort()).toEqual(['paths', 'pointSites'])
  })

  it('the carve spacing law: tolerance x 8 within [0.05, 0.5] mm, raised for a long outline', () => {
    const small = { outer: rect(40, 10), holes: [] }
    expect(service.carveSpacing(small, 0.01)).toBe(0.08)
    expect(service.carveSpacing(small, 0.001)).toBe(0.05)
    expect(service.carveSpacing(small, 0.1)).toBe(0.5)
    expect(service.carveSpacing({ outer: rect(20_000, 20_000), holes: [] }, 0.01)).toBeCloseTo(80_000 / 60_000, 12)
    expect(service.floorCoreSpacing(small, 1)).toBe(0.25)
    expect(service.floorCoreSpacing(small, 0.1)).toBe(0.05)
  })
})

describe('WO-3038 determinism', () => {
  it('the same input gives the same axis, from one service or a fresh one', () => {
    const region = buildRegions(outlineTextToContours('A', 20).map(c => c.points))[0]
    const first = JSON.stringify(service.axis(region, { spacing: 0.1 }))
    expect((JSON.parse(first) as kernel.AxisPath[]).length).toBeGreaterThan(2)
    expect(JSON.stringify(service.axis(region, { spacing: 0.1 }))).toBe(first)
    expect(JSON.stringify(kernel.createMedialService().axis(structuredClone(region), { spacing: 0.1 }))).toBe(first)
    // The service never mutates its input.
    const copy = structuredClone(region)
    service.axis(region, { spacing: 0.1 })
    expect(region).toEqual(copy)
  })
})
